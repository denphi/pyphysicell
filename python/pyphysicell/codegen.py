"""Emit a Model as plain Python source.

This is the other direction of the file round trip: a PhysiCell project read
from XML can be written back out as a self-contained script that builds the
same model with no XML, no CSV and no PhysiCell checkout.  The generated code
is meant to be read and edited, so it names every value instead of looping.
"""

from __future__ import annotations

import textwrap

from .model import Model

_HDR = "# Generated by pyphysicell.codegen from {src}.\n# Values are PhysiCell's: minutes, microns, and each substrate's own units.\n"


def _n(v: float) -> str:
    """Exact float literal.  Always a float, so the regenerated model hashes
    identically to the one it came from (1 and 1.0 are the same number but not
    the same JSON)."""
    return repr(float(v))


def _kw(**kw) -> str:
    return ", ".join(f"{k}={v}" for k, v in kw.items())


def _wrap(prefix: str, items: list[str], suffix: str = "]", width: int = 96) -> str:
    one = prefix + ", ".join(items) + suffix
    if len(one) <= width:
        return one
    inner = textwrap.indent(",\n".join(items), "    ")
    return f"{prefix}\n{inner},\n{suffix}"


def _substrate(s) -> str:
    faces = ", ".join(f'"{f}": ({e}, {_n(v)})' for f, (e, v) in sorted(s.dirichlet_faces.items()))
    args = [f'"{s.name}"',
            f"diffusion_coefficient={_n(s.diffusion_coefficient)}",
            f"decay_rate={_n(s.decay_rate)}",
            f"initial_condition={_n(s.initial_condition)}"]
    args.append(f"dirichlet_enabled={s.dirichlet_enabled}, "
                f"dirichlet_value={_n(s.dirichlet_value)}")
    if faces:
        args.append("dirichlet_faces={" + faces + "}")
    return _wrap("pc.Substrate(", args, ")")


def _cycle(c) -> str:
    rates = ", ".join(f"({i}, {j}): {_n(r)}" for (i, j), r in sorted(c.transition_rates.items()))
    fixed = ", ".join(f"({i}, {j}): {v}" for (i, j), v in sorted(c.fixed_duration.items()))
    out = (f'pc.Cycle(code={c.code}, name="{c.name}",\n'
           f"         transition_rates={{{rates}}},\n"
           f"         fixed_duration={{{fixed}}}")
    if c.asymmetric_division:
        ad = ", ".join(f'"{k}": {_n(v)}' for k, v in c.asymmetric_division.items())
        out += f",\n         asymmetric_division={{{ad}}}"
    return out + ")"


def _death(d) -> str:
    durs = ", ".join(f"{k}: {_n(v)}" for k, v in sorted(d.phase_durations.items()))
    return (f'pc.DeathModel(code={d.code}, name="{d.name}", death_rate={_n(d.death_rate)},\n'
            f"              phase_durations={{{durs}}},\n"
            f"              unlysed_fluid_change_rate={_n(d.unlysed_fluid_change_rate)},\n"
            f"              lysed_fluid_change_rate={_n(d.lysed_fluid_change_rate)},\n"
            f"              cytoplasmic_biomass_change_rate={_n(d.cytoplasmic_biomass_change_rate)},\n"
            f"              nuclear_biomass_change_rate={_n(d.nuclear_biomass_change_rate)},\n"
            f"              calcification_rate={_n(d.calcification_rate)},\n"
            f"              relative_rupture_volume={_n(d.relative_rupture_volume)})")


def _cell_type(ct, var: str) -> list[str]:
    out = [f'{var} = pc.CellType("{ct.name}", ID={ct.ID})',
           f"{var}.cycle = {_cycle(ct.cycle)}"]
    if ct.deaths:
        deaths = ",\n    ".join(f'"{k}": {_death(v)}' for k, v in ct.deaths.items())
        out.append(f"{var}.deaths = {{\n    {deaths}}}")
    v = ct.volume
    out.append(f"{var}.volume = pc.Volume(" + _kw(
        total=_n(v.total), fluid_fraction=_n(v.fluid_fraction), nuclear=_n(v.nuclear),
        fluid_change_rate=_n(v.fluid_change_rate),
        cytoplasmic_biomass_change_rate=_n(v.cytoplasmic_biomass_change_rate),
        nuclear_biomass_change_rate=_n(v.nuclear_biomass_change_rate),
        calcified_fraction=_n(v.calcified_fraction),
        calcification_rate=_n(v.calcification_rate),
        relative_rupture_volume=_n(v.relative_rupture_volume)) + ")")
    m = ct.mechanics
    aff = ", ".join(f'"{k}": {_n(x)}' for k, x in m.adhesion_affinities.items())
    out.append(f"{var}.mechanics = pc.Mechanics(" + _kw(
        cell_cell_adhesion_strength=_n(m.cell_cell_adhesion_strength),
        cell_cell_repulsion_strength=_n(m.cell_cell_repulsion_strength),
        relative_maximum_adhesion_distance=_n(m.relative_maximum_adhesion_distance),
        attachment_elastic_constant=_n(m.attachment_elastic_constant),
        attachment_rate=_n(m.attachment_rate),
        detachment_rate=_n(m.detachment_rate),
        maximum_number_of_attachments=m.maximum_number_of_attachments,
        cell_BM_adhesion_strength=_n(m.cell_BM_adhesion_strength),
        cell_BM_repulsion_strength=_n(m.cell_BM_repulsion_strength)) +
        (f", adhesion_affinities={{{aff}}}" if aff else "") + ")")
    mo = ct.motility
    sens = ", ".join(f'"{k}": {_n(x)}' for k, x in mo.sensitivities.items())
    out.append(f"{var}.motility = pc.Motility(" + _kw(
        speed=_n(mo.speed), persistence_time=_n(mo.persistence_time),
        migration_bias=_n(mo.migration_bias), enabled=mo.enabled, use_2D=mo.use_2D,
        chemotaxis_enabled=mo.chemotaxis_enabled,
        chemotaxis_substrate=f'"{mo.chemotaxis_substrate}"',
        chemotaxis_direction=_n(mo.chemotaxis_direction),
        advanced_chemotaxis=mo.advanced_chemotaxis,
        normalize_each_gradient=mo.normalize_each_gradient) +
        (f", sensitivities={{{sens}}}" if sens else "") + ")")
    if ct.secretion:
        entries = ",\n    ".join(
            f'"{k}": pc.SecretionEntry(' + _kw(
                secretion_rate=_n(e.secretion_rate), secretion_target=_n(e.secretion_target),
                uptake_rate=_n(e.uptake_rate), net_export_rate=_n(e.net_export_rate)) + ")"
            for k, e in ct.secretion.items())
        out.append(f"{var}.secretion = {{\n    {entries}}}")
    if ct.custom_data:
        cd = ", ".join(f'"{k}": {_n(v)}' for k, v in ct.custom_data.items())
        out.append(f"{var}.custom_data = {{{cd}}}")
    it = ct.interactions
    if (it.live_phagocytosis_rates or it.attack_rates or it.fusion_rates
            or it.transformation_rates or it.immunogenicities
            or it.apoptotic_phagocytosis_rate or it.necrotic_phagocytosis_rate
            or it.other_dead_phagocytosis_rate or it.damage_rate or it.damage_repair_rate
            or it.attack_damage_rate != 1.0 or it.attack_duration != 0.1):
        def _d2(d):
            return "{" + ", ".join(f'"{k}": {_n(v)}' for k, v in d.items()) + "}"
        out.append(f"{var}.interactions = pc.Interactions(\n"
                   f"    apoptotic_phagocytosis_rate={_n(it.apoptotic_phagocytosis_rate)},\n"
                   f"    necrotic_phagocytosis_rate={_n(it.necrotic_phagocytosis_rate)},\n"
                   f"    other_dead_phagocytosis_rate={_n(it.other_dead_phagocytosis_rate)},\n"
                   f"    attack_damage_rate={_n(it.attack_damage_rate)},\n"
                   f"    attack_duration={_n(it.attack_duration)},\n"
                   f"    damage_rate={_n(it.damage_rate)},\n"
                   f"    damage_repair_rate={_n(it.damage_repair_rate)},\n"
                   f"    live_phagocytosis_rates={_d2(it.live_phagocytosis_rates)},\n"
                   f"    attack_rates={_d2(it.attack_rates)},\n"
                   f"    fusion_rates={_d2(it.fusion_rates)},\n"
                   f"    transformation_rates={_d2(it.transformation_rates)},\n"
                   f"    immunogenicities={_d2(it.immunogenicities)})")
    if getattr(ct, "distributions", None):
        items = [("pc.ParameterDistribution(behavior={b!r}, kind={k!r}, enabled={e}, "
                  "check_base={c}, parameters={{{p}}})").format(
                     b=d.behavior, k=d.kind, e=d.enabled, c=d.check_base,
                     p=", ".join(f'"{key}": {_n(v)}' for key, v in d.parameters.items()))
                 for d in ct.distributions]
        out.append(f"{var}.distributions = [\n    " + ",\n    ".join(items) + "]")
    if ct.custom_conserved:
        cc = ", ".join(f'"{k}": {v}' for k, v in ct.custom_conserved.items())
        out.append(f"{var}.custom_conserved = {{{cc}}}")
    return out


def _rules(rules) -> str:
    if not rules:
        return "model.rules = []"
    items = [('pc.Rule("{}", "{}", "{}", "{}", max_response={}, half_max={}, hill_power={}, '
              "apply_to_dead={})").format(r.cell_type, r.signal, r.direction, r.behavior,
                                          _n(r.max_response), _n(r.half_max), _n(r.hill_power),
                                          r.apply_to_dead)
             for r in rules]
    return "model.rules = [\n    " + ",\n    ".join(items) + ",\n]"


def _initial(model: Model, style: str, csv_path: str = "") -> str:
    if style == "none":
        return "# (initial conditions omitted)"
    if style == "csv":
        if not model.initial_cells:
            return ("# This project seeds its cells in C++ (setup_tissue); the port or\n"
                    "# pyphysicell.initial.auto places them at run time.\n"
                    "initial_cells, placement = pc.initial.auto(model)\n"
                    "model.initial_cells = initial_cells\n"
                    "print(placement)")
        counts: dict[str, int] = {}
        for *_xyz, name in model.initial_cells:
            counts[name] = counts.get(name, 0) + 1
        tally = ", ".join(f"{v} {k}" for k, v in counts.items())
        return (f"# Initial conditions live beside this notebook ({tally}).\n"
                f"CELLS = DATA / {csv_path!r}\n"
                "model.initial_cells = pc.read_cells_csv(CELLS, model.cell_type_names)\n"
                "print(f'{len(model.initial_cells)} cells from {CELLS.name}')")
    if not model.initial_cells:
        return ("# This project seeds its cells in C++ (setup_tissue); pyphysicell.initial.auto\n"
                "# ports that placement from the project's own user parameters.\n"
                "initial_cells, placement = pc.initial.auto(model)\n"
                "model.initial_cells = initial_cells\n"
                "print(placement)")
    if style == "auto":
        return "initial_cells, placement = pc.initial.auto(model)\nmodel.initial_cells = initial_cells"
    # carried in source order, so the notebook needs no cells.csv and the model
    # hashes the same as the one read from the project
    items = [f'({_n(x)}, {_n(y)}, {_n(z)}, "{name}")' for (x, y, z, name) in model.initial_cells]
    rows = []
    for i in range(0, len(items), 3):
        rows.append("    " + ", ".join(items[i:i + 3]) + ",")
    counts: dict[str, int] = {}
    for *_xyz, name in model.initial_cells:
        counts[name] = counts.get(name, 0) + 1
    tally = ", ".join(f"{v} {k}" for k, v in counts.items())
    return ("# Initial cells, carried here so the notebook needs no cells.csv "
            f"({tally}).\nmodel.initial_cells = [\n" + "\n".join(rows) + "\n]")


def to_python(model: Model, src: str = "a PhysiCell project", initial: str = "literal",
              var: str = "model", csv_path: str = "") -> str:
    """Return Python source that rebuilds `model` with no external files.

    `initial`: "literal" writes the cells out (or ports the C++ placement with
    pyphysicell.initial.auto when the project has none), "csv" reads them from a
    file beside the script, "auto" always ports, and "none" omits them.
    """
    d, t, s = model.domain, model.time, model.save
    lines = [_HDR.format(src=src), "",
             f'{var} = pc.Model(name="{model.name}")',
             f"{var}.domain = pc.Domain(" + _kw(
                 x_min=_n(d.x_min), x_max=_n(d.x_max), y_min=_n(d.y_min), y_max=_n(d.y_max),
                 z_min=_n(d.z_min), z_max=_n(d.z_max), dx=_n(d.dx), dy=_n(d.dy), dz=_n(d.dz),
                 use_2D=d.use_2D) + ")",
             f"{var}.time = pc.Time(" + _kw(
                 dt_diffusion=_n(t.dt_diffusion), dt_mechanics=_n(t.dt_mechanics),
                 dt_phenotype=_n(t.dt_phenotype), max_time=_n(t.max_time),
                 time_units=f'"{t.time_units}"', space_units=f'"{t.space_units}"') + ")",
             f"{var}.random_seed = {model.random_seed}",
             f"{var}.virtual_wall = {model.virtual_wall}",
             f"{var}.omp_num_threads = {model.omp_num_threads}",
             f"{var}.calculate_gradients = {model.calculate_gradients}",
             f"{var}.track_internalized_substrates = {model.track_internalized_substrates}",
             f"{var}.disable_automated_spring_adhesions = "
             f"{model.disable_automated_spring_adhesions}",
             f"{var}.legacy_division_orientation = {model.legacy_division_orientation}",
             f'{var}.save = pc.SaveOptions(folder="{s.folder}", full_interval={_n(s.full_interval)}, '
             f"full_enabled={s.full_enabled}, svg_interval={_n(s.svg_interval)}, "
             f"svg_enabled={s.svg_enabled})",
             ""]
    lines.append("# --- substrates " + "-" * 62)
    lines.append(_wrap(f"{var}.substrates = [", [_substrate(x) for x in model.substrates]))
    lines.append("")
    lines.append("# --- cell types " + "-" * 62)
    names = []
    for i, ct in enumerate(model.cell_types):
        v = f"ct{i}"
        names.append(v)
        lines += _cell_type(ct, v)
        lines.append("")
    lines.append(f"{var}.cell_types = [{', '.join(names)}]")
    lines.append("")
    if model.user_parameters:
        ups = ", ".join(f'"{k}": {v!r}' for k, v in model.user_parameters.items())
        lines.append(f"{var}.user_parameters = {{{ups}}}")
        lines.append("")
    lines.append("# --- rules (cell behavior hypothesis grammar) " + "-" * 33)
    lines.append(_rules(model.rules))
    lines.append("")
    lines.append("# --- initial conditions " + "-" * 54)
    lines.append(_initial(model, initial, csv_path))
    return "\n".join(lines)
